`timescale 1ns/1ps

//============================================================
// File Name   : key_scan.v
// Project     : Smart Access Control
// Device      : Anlogic EG4S20BG256
// Board       : DMZ_EG4S20
//
// Function:
//   1. Scan 4x4 matrix keyboard
//   2. Synchronize column inputs
//   3. Debounce keys
//   4. Convert key position to 4-bit key code
//   5. Generate one-clock key_valid pulse
//
// Matrix keyboard:
//
//             COL0 COL1 COL2 COL3
//      ROW0    0    1    2    3
//      ROW1    4    5    6    7
//      ROW2    8    9    A    B
//      ROW3    C    D    E    F
//
// Electrical characteristic:
//   Column lines are pulled HIGH.
//   One row is driven LOW at a time.
//
// Example:
//   key_row = 1110
//   key_col = 1011
//
//   ROW0 active
//   COL2 low
//
//   => KEY2 pressed
//============================================================

module key_scan #(

    parameter integer CLK_FREQ_HZ = 50000000,

    //--------------------------------------------------------
    // 每一行保持100us
    //
    // 每秒扫描10000行
    // 4行组成一帧
    //
    // 完整键盘扫描频率：
    // 10000 / 4 = 2500 Hz
    //--------------------------------------------------------
    parameter integer ROW_SCAN_HZ = 10000,

    //--------------------------------------------------------
    // 消抖时间
    //--------------------------------------------------------
    parameter integer DEBOUNCE_MS = 20

)(
    input  wire       clk,
    input  wire       rst_n,

    //--------------------------------------------------------
    // 键盘列输入
    //
    // 无按键：1111
    // 按键按下：对应列变为0
    //--------------------------------------------------------
    input  wire [3:0] key_col,

    //--------------------------------------------------------
    // 键盘行扫描输出
    //--------------------------------------------------------
    output reg  [3:0] key_row,

    //--------------------------------------------------------
    // 按键事件
    //
    // 检测到一次新的稳定按键后
    // key_valid只保持一个clk
    //--------------------------------------------------------
    output reg        key_valid,

    //--------------------------------------------------------
    // 按键编号0~15
    //--------------------------------------------------------
    output reg  [3:0] key_code
);


    //========================================================
    // 扫描参数
    //========================================================

    localparam integer SCAN_DIV =
        CLK_FREQ_HZ / ROW_SCAN_HZ;

    //--------------------------------------------------------
    // 在每一行保持时间的中间位置采样
    //
    // 行信号刚切换时不立即读取列信号，
    // 给电路足够的稳定时间。
    //--------------------------------------------------------
    localparam integer SAMPLE_POINT =
        SCAN_DIV / 2;


    //--------------------------------------------------------
    // 一帧 = 4行
    //
    // Full Scan Frequency:
    // ROW_SCAN_HZ / 4
    //--------------------------------------------------------

    localparam integer FRAME_HZ =
        ROW_SCAN_HZ / 4;


    //--------------------------------------------------------
    // 20ms需要多少完整扫描帧
    //
    // 默认：
    //
    // FRAME_HZ = 2500Hz
    //
    // 20ms：
    //
    // 2500 * 20 / 1000
    // = 50帧
    //--------------------------------------------------------

    localparam integer DEBOUNCE_FRAMES =
        (FRAME_HZ * DEBOUNCE_MS) / 1000;


    //========================================================
    // Column输入两级同步
    //
    // 外部按键信号相对于50MHz时钟是异步信号。
    // 使用两级寄存器降低亚稳态风险。
    //========================================================

    reg [3:0] col_ff1;
    reg [3:0] col_ff2;


    always @(posedge clk or negedge rst_n)
    begin

        if (!rst_n)
        begin

            col_ff1 <= 4'b1111;
            col_ff2 <= 4'b1111;

        end

        else
        begin

            col_ff1 <= key_col;
            col_ff2 <= col_ff1;

        end

    end


    //========================================================
    // 矩阵扫描
    //========================================================

    reg [31:0] scan_cnt;

    reg [1:0] row_index;


    //--------------------------------------------------------
    // 保存16个按键状态
    //
    // 1 = 按下
    // 0 = 未按
    //
    // key_map[3:0]   -> ROW0
    // key_map[7:4]   -> ROW1
    // key_map[11:8]  -> ROW2
    // key_map[15:12] -> ROW3
    //--------------------------------------------------------

    reg [15:0] key_map;


    //--------------------------------------------------------
    // 一帧扫描完成脉冲
    //--------------------------------------------------------

    reg frame_done;


    always @(posedge clk or negedge rst_n)
    begin

        if (!rst_n)
        begin

            scan_cnt   <= 32'd0;

            row_index  <= 2'd0;

            //------------------------------------------------
            // ROW0首先有效
            //
            // 0为有效扫描电平
            //------------------------------------------------
            key_row    <= 4'b1110;

            key_map    <= 16'd0;

            frame_done <= 1'b0;

        end

        else
        begin

            //------------------------------------------------
            // 默认frame_done为0
            //------------------------------------------------
            frame_done <= 1'b0;


            //================================================
            // 在当前行稳定一段时间以后读取列
            //================================================

            if (scan_cnt == SAMPLE_POINT)
            begin

                case (row_index)

                    //----------------------------------------
                    // ROW0
                    //----------------------------------------
                    2'd0:
                    begin

                        key_map[3:0]
                            <= ~col_ff2;

                    end


                    //----------------------------------------
                    // ROW1
                    //----------------------------------------
                    2'd1:
                    begin

                        key_map[7:4]
                            <= ~col_ff2;

                    end


                    //----------------------------------------
                    // ROW2
                    //----------------------------------------
                    2'd2:
                    begin

                        key_map[11:8]
                            <= ~col_ff2;

                    end


                    //----------------------------------------
                    // ROW3
                    //----------------------------------------
                    2'd3:
                    begin

                        key_map[15:12]
                            <= ~col_ff2;

                        //------------------------------------------------
                        // ROW3采样完成
                        // 表示16个按键全部扫描了一遍
                        //------------------------------------------------
                        frame_done
                            <= 1'b1;

                    end

                endcase

            end


            //================================================
            // 当前行扫描时间结束
            //================================================

            if (scan_cnt >= SCAN_DIV - 1)
            begin

                scan_cnt <= 32'd0;


                //------------------------------------------------
                // 切换到下一行
                //------------------------------------------------
                case (row_index)

                    2'd0:
                    begin

                        row_index <= 2'd1;

                        key_row <= 4'b1101;

                    end


                    2'd1:
                    begin

                        row_index <= 2'd2;

                        key_row <= 4'b1011;

                    end


                    2'd2:
                    begin

                        row_index <= 2'd3;

                        key_row <= 4'b0111;

                    end


                    default:
                    begin

                        row_index <= 2'd0;

                        key_row <= 4'b1110;

                    end

                endcase

            end

            else
            begin

                scan_cnt <= scan_cnt + 1'b1;

            end

        end

    end


    //========================================================
    // 16-bit按键状态 -> 按键编号
    //
    // 只接受“一次按一个键”
    //
    // 多键同时按下时raw_valid=0，
    // 防止密码系统出现模糊输入。
    //========================================================

    reg       raw_valid;
    reg [3:0] raw_code;


    always @(*)
    begin

        raw_valid = 1'b1;

        raw_code = 4'd0;


        case (key_map)

            16'h0001:
                raw_code = 4'h0;

            16'h0002:
                raw_code = 4'h1;

            16'h0004:
                raw_code = 4'h2;

            16'h0008:
                raw_code = 4'h3;


            16'h0010:
                raw_code = 4'h4;

            16'h0020:
                raw_code = 4'h5;

            16'h0040:
                raw_code = 4'h6;

            16'h0080:
                raw_code = 4'h7;


            16'h0100:
                raw_code = 4'h8;

            16'h0200:
                raw_code = 4'h9;

            16'h0400:
                raw_code = 4'hA;

            16'h0800:
                raw_code = 4'hB;


            16'h1000:
                raw_code = 4'hC;

            16'h2000:
                raw_code = 4'hD;

            16'h4000:
                raw_code = 4'hE;

            16'h8000:
                raw_code = 4'hF;


            //------------------------------------------------
            // 没有按键或者多个按键同时按下
            //------------------------------------------------
            default:
            begin

                raw_valid = 1'b0;
                raw_code  = 4'd0;

            end

        endcase

    end


    //========================================================
    // 消抖
    //
    // 将“有没有按键 + 按键编号”
    // 一起作为稳定性判断对象。
    //
    // bit[4]   : valid
    // bit[3:0] : code
    //========================================================

    wire [4:0] raw_token;


    assign raw_token =
        {
            raw_valid,
            raw_code
        };


    //--------------------------------------------------------
    // 当前正在观察的候选状态
    //--------------------------------------------------------

    reg [4:0] candidate_token;


    //--------------------------------------------------------
    // 已经确认稳定的状态
    //--------------------------------------------------------

    reg [4:0] stable_token;


    //--------------------------------------------------------
    // 连续稳定扫描次数
    //--------------------------------------------------------

    reg [15:0] debounce_cnt;


    always @(posedge clk or negedge rst_n)
    begin

        if (!rst_n)
        begin

            candidate_token <= 5'd0;

            stable_token <= 5'd0;

            debounce_cnt <= 16'd0;

            key_valid <= 1'b0;

            key_code <= 4'd0;

        end

        else
        begin

            //------------------------------------------------
            // key_valid默认只维持一个系统时钟
            //------------------------------------------------
            key_valid <= 1'b0;


            //------------------------------------------------
            // 每扫描完整个4×4键盘一次
            // 才进行一次消抖判断
            //------------------------------------------------
            if (frame_done)
            begin


                //============================================
                // 当前状态和上一次候选状态相同
                //============================================

                if (raw_token == candidate_token)
                begin

                    if (debounce_cnt < DEBOUNCE_FRAMES)
                    begin

                        debounce_cnt
                            <= debounce_cnt + 1'b1;

                    end


                    //------------------------------------------------
                    // 持续时间达到消抖要求
                    //------------------------------------------------
                    if (
                        debounce_cnt
                        ==
                        DEBOUNCE_FRAMES - 1
                    )
                    begin

                        //------------------------------------------------
                        // 只有稳定状态真正发生变化时处理
                        //------------------------------------------------
                        if (stable_token != candidate_token)
                        begin

                            stable_token
                                <= candidate_token;


                            //------------------------------------------------
                            // 从“无按键”
                            // 转变到“某个有效按键”
                            //
                            // 产生一次按键事件
                            //------------------------------------------------
                            if (candidate_token[4])
                            begin

                                key_code
                                    <= candidate_token[3:0];

                                key_valid
                                    <= 1'b1;

                            end

                        end

                    end

                end


                //============================================
                // 当前按键状态发生变化
                //
                // 重新开始消抖计数
                //============================================

                else
                begin

                    candidate_token
                        <= raw_token;

                    debounce_cnt
                        <= 16'd1;

                end

            end

        end

    end


endmodule