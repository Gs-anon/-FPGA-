`timescale 1ns/1ps

//============================================================
// File Name   : password_fsm.v
// Project     : Smart Access Control
// Device      : Anlogic EG4S20BG256
//
// Function:
//   1. Receive key event from key_scan
//   2. Accept numeric keys 0~9
//   3. E = Clear
//   4. F = Enter
//   5. Compare 4-digit password
//
// Default password:
//   2 5 8 0
//
// Output:
//   password_ok   : one-clock pulse
//   password_fail : one-clock pulse
//============================================================

module password_fsm #(

    //--------------------------------------------------------
    // 4位密码
    //
    // 2 5 8 0
    // ↓
    // 16'h2580
    //--------------------------------------------------------
    parameter [15:0] PASSWORD = 16'h2580

)(
    input  wire        clk,
    input  wire        rst_n,

    //--------------------------------------------------------
    // 来自key_scan.v
    //--------------------------------------------------------
    input  wire        key_valid,
    input  wire [3:0]  key_code,

    //--------------------------------------------------------
    // 密码判断结果
    //
    // 两个信号都只保持一个clk
    //--------------------------------------------------------
    output reg         password_ok,
    output reg         password_fail,

    //--------------------------------------------------------
    // 当前已经输入的数字数量
    //
    // 0~4
    //--------------------------------------------------------
    output reg [2:0]   digit_count,

    //--------------------------------------------------------
    // 当前输入内容
    //
    // 后面可用于数码管显示/debug
    //--------------------------------------------------------
    output reg [15:0]  entered_password
);


    //========================================================
    // 按键定义
    //========================================================

    localparam [3:0] KEY_CLEAR = 4'hE;

    localparam [3:0] KEY_ENTER = 4'hF;


    //========================================================
    // 密码输入控制
    //========================================================

    always @(posedge clk or negedge rst_n)
    begin

        if (!rst_n)
        begin

            entered_password <= 16'h0000;

            digit_count <= 3'd0;

            password_ok <= 1'b0;

            password_fail <= 1'b0;

        end

        else
        begin

            //------------------------------------------------
            // 默认情况下结果信号为0
            //
            // 所以OK/FAIL只会持续一个系统时钟
            //------------------------------------------------
            password_ok <= 1'b0;

            password_fail <= 1'b0;


            //------------------------------------------------
            // 只有key_valid=1才处理key_code
            //------------------------------------------------
            if (key_valid)
            begin


                //============================================
                // CLEAR键
                //============================================

                if (key_code == KEY_CLEAR)
                begin

                    entered_password <= 16'h0000;

                    digit_count <= 3'd0;

                end


                //============================================
                // ENTER键
                //============================================

                else if (key_code == KEY_ENTER)
                begin

                    //------------------------------------------------
                    // 必须正好输入4位
                    // 并且密码完全相同
                    //------------------------------------------------
                    if (
                        (digit_count == 3'd4)
                        &&
                        (entered_password == PASSWORD)
                    )
                    begin

                        password_ok <= 1'b1;

                    end

                    else
                    begin

                        password_fail <= 1'b1;

                    end


                    //------------------------------------------------
                    // 一次密码判断结束后
                    // 自动清空输入缓冲
                    //------------------------------------------------
                    entered_password <= 16'h0000;

                    digit_count <= 3'd0;

                end


                //============================================
                // 数字键 0~9
                //============================================

                else if (key_code <= 4'd9)
                begin

                    //------------------------------------------------
                    // 最多输入4位数字
                    //------------------------------------------------
                    if (digit_count < 3'd4)
                    begin

                        //------------------------------------------------
                        // 左移一位十六进制数字
                        //
                        // 例如：
                        //
                        // 0000
                        // ↓ 输入2
                        // 0002
                        //
                        // ↓ 输入5
                        // 0025
                        //
                        // ↓ 输入8
                        // 0258
                        //
                        // ↓ 输入0
                        // 2580
                        //------------------------------------------------

                        entered_password
                            <= {
                                entered_password[11:0],
                                key_code
                            };


                        digit_count
                            <= digit_count + 1'b1;

                    end

                end


                //============================================
                // A/B/C/D
                //
                // 第一版暂时不处理
                //============================================

                else
                begin

                    entered_password
                        <= entered_password;

                    digit_count
                        <= digit_count;

                end

            end

        end

    end


endmodule