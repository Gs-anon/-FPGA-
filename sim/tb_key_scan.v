`timescale 1ns/1ps

//============================================================
// File Name   : tb_key_scan.v
// Description : key_scan.v ModelSim Testbench
//
// 模拟内容：
//
// 1. 4x4矩阵键盘电气行为
// 2. ROW扫描：
//      1110
//      1101
//      1011
//      0111
//
// 3. 测试按键：
//      KEY2
//      KEY9
//      KEYF
//
// 4. 验证：
//      key_valid只产生一次
//      长按不会连续重复输出
//      松开后可以重新按键
//
// 注意：
// 为加快ModelSim仿真，下面把扫描和消抖参数缩短。
// 真正上板时仍使用key_scan.v默认参数。
//============================================================

module tb_key_scan;


//============================================================
// Testbench信号
//============================================================

reg clk;

reg rst_n;


//------------------------------------------------------------
// FPGA输出给键盘的行扫描信号
//------------------------------------------------------------

wire [3:0] key_row;


//------------------------------------------------------------
// 键盘返回给FPGA的列信号
//
// Testbench负责模拟这个信号。
//------------------------------------------------------------

reg [3:0] key_col;


//------------------------------------------------------------
// DUT输出
//------------------------------------------------------------

wire       key_valid;

wire [3:0] key_code;


//============================================================
// 模拟“当前有没有按键被按下”
//============================================================

reg       key_pressed;

reg [3:0] pressed_code;


//============================================================
// 实例化DUT
//
// 这里特意把参数缩小，只为了加快仿真。
//
// 实际板子：
// CLK_FREQ_HZ = 50,000,000
// ROW_SCAN_HZ = 10,000
// DEBOUNCE_MS = 20
//
// 仿真这里：
//
// SCAN_DIV = 1000 / 100 = 10
//
// 每10个clk换一行。
// 四行共40个clk完成一次完整扫描。
//
// DEBOUNCE_FRAMES =
// (100/4)*80/1000
// = 2
//
// 即连续稳定约2帧即可确认按键。
//============================================================

key_scan #(

    .CLK_FREQ_HZ
    (
        1000
    ),

    .ROW_SCAN_HZ
    (
        100
    ),

    .DEBOUNCE_MS
    (
        80
    )

)
uut
(

    .clk
    (
        clk
    ),

    .rst_n
    (
        rst_n
    ),

    .key_col
    (
        key_col
    ),

    .key_row
    (
        key_row
    ),

    .key_valid
    (
        key_valid
    ),

    .key_code
    (
        key_code
    )

);


//============================================================
// 50MHz时钟
//
// 周期：20ns
//============================================================

initial
begin

    clk = 1'b0;

    forever
        #10 clk = ~clk;

end


//============================================================
// 模拟真实4x4矩阵键盘
//
// pressed_code:
//
// bit[3:2] = ROW编号
// bit[1:0] = COL编号
//
// 例如：
//
// KEY2 = 0010
//
// ROW = 00 = ROW0
// COL = 10 = COL2
//
// 当FPGA：
//
// key_row = 1110
//
// 即ROW0被拉低时，Testbench返回：
//
// key_col = 1011
//
// 即COL2也变成低电平。
//============================================================

always @(*)
begin

    //--------------------------------------------------------
    // 默认没有按键：
    //
    // 所有列都是高电平
    //--------------------------------------------------------

    key_col = 4'b1111;


    //--------------------------------------------------------
    // 如果有人按键
    //--------------------------------------------------------

    if (key_pressed)
    begin

        case (pressed_code[3:2])


            //------------------------------------------------
            // ROW0
            //------------------------------------------------
            2'd0:
            begin

                if (key_row == 4'b1110)
                begin

                    key_col[pressed_code[1:0]]
                        = 1'b0;

                end

            end


            //------------------------------------------------
            // ROW1
            //------------------------------------------------
            2'd1:
            begin

                if (key_row == 4'b1101)
                begin

                    key_col[pressed_code[1:0]]
                        = 1'b0;

                end

            end


            //------------------------------------------------
            // ROW2
            //------------------------------------------------
            2'd2:
            begin

                if (key_row == 4'b1011)
                begin

                    key_col[pressed_code[1:0]]
                        = 1'b0;

                end

            end


            //------------------------------------------------
            // ROW3
            //------------------------------------------------
            2'd3:
            begin

                if (key_row == 4'b0111)
                begin

                    key_col[pressed_code[1:0]]
                        = 1'b0;

                end

            end


        endcase

    end

end


//============================================================
// 模拟按下一个键
//============================================================

task press_key;

    input [3:0] code;

    begin

        //----------------------------------------------------
        // 在下降沿改变外部输入，
        // 避免和DUT的posedge采样竞争
        //----------------------------------------------------

        @(negedge clk);

        pressed_code =
            code;

        key_pressed =
            1'b1;


        $display(
            "PRESS KEY %h",
            code
        );

    end

endtask


//============================================================
// 模拟松开按键
//============================================================

task release_key;

    begin

        @(negedge clk);

        key_pressed =
            1'b0;


        $display(
            "RELEASE KEY"
        );


        //----------------------------------------------------
        // 等待几帧，让DUT确认已经松开
        //----------------------------------------------------

        repeat(160)
            @(posedge clk);

    end

endtask


//============================================================
// 等待并检查一个按键事件
//============================================================

task expect_key;

    input [3:0] expected_code;

    integer i;

    reg found;


    begin

        found = 1'b0;


        //----------------------------------------------------
        // 最多等待200个clk
        //----------------------------------------------------

        for
        (
            i = 0;
            i < 200;
            i = i + 1
        )
        begin

            @(posedge clk);

            #1;


            if (key_valid)
            begin

                found = 1'b1;


                if (key_code == expected_code)
                begin

                    $display(
                        "PASS : expected=%h actual=%h",
                        expected_code,
                        key_code
                    );

                end

                else
                begin

                    $display(
                        "FAIL : expected=%h actual=%h",
                        expected_code,
                        key_code
                    );

                end


                //------------------------------------------------
                // 找到以后直接退出等待意义
                //
                // Verilog-2001没有break，
                // 后续循环仍执行但不重复判断。
                //------------------------------------------------

                i = 200;

            end

        end


        if (!found)
        begin

            $display(
                "FAIL : KEY %h TIMEOUT",
                expected_code
            );

        end

    end

endtask


//============================================================
// 检查长按时不会重复产生key_valid
//============================================================

task check_no_repeat;

    integer i;

    integer repeat_count;


    begin

        repeat_count = 0;


        //----------------------------------------------------
        // 持续观察120个clk
        //----------------------------------------------------

        for
        (
            i = 0;
            i < 120;
            i = i + 1
        )
        begin

            @(posedge clk);

            #1;


            if (key_valid)
            begin

                repeat_count =
                    repeat_count + 1;

            end

        end


        if (repeat_count == 0)
        begin

            $display(
                "PASS : HOLD KEY HAS NO REPEAT"
            );

        end

        else
        begin

            $display(
                "FAIL : HOLD KEY REPEATED %0d TIMES",
                repeat_count
            );

        end

    end

endtask


//============================================================
// 主测试流程
//============================================================

initial
begin

    //--------------------------------------------------------
    // 初始化
    //--------------------------------------------------------

    rst_n =
        1'b0;

    key_pressed =
        1'b0;

    pressed_code =
        4'd0;


    $display("");
    $display("======================================");
    $display(" KEY SCAN SIMULATION START");
    $display("======================================");
    $display("");


    //--------------------------------------------------------
    // 复位
    //--------------------------------------------------------

    #200;

    rst_n =
        1'b1;


    //--------------------------------------------------------
    // 让扫描器先运行一段时间
    //--------------------------------------------------------

    repeat(100)
        @(posedge clk);


    //========================================================
    // TEST 1
    //
    // 按KEY2
    //
    // ROW0 COL2
    //========================================================

    $display("");
    $display("TEST 1 : KEY 2");


    press_key(
        4'h2
    );


    expect_key(
        4'h2
    );


    //--------------------------------------------------------
    // 继续按住
    //
    // 不应该再次产生key_valid
    //--------------------------------------------------------

    check_no_repeat();


    release_key();



    //========================================================
    // TEST 2
    //
    // 按KEY9
    //
    // ROW2 COL1
    //========================================================

    $display("");
    $display("TEST 2 : KEY 9");


    press_key(
        4'h9
    );


    expect_key(
        4'h9
    );


    release_key();



    //========================================================
    // TEST 3
    //
    // 按KEYF
    //
    // ROW3 COL3
    //========================================================

    $display("");
    $display("TEST 3 : KEY F");


    press_key(
        4'hF
    );


    expect_key(
        4'hF
    );


    release_key();



    //========================================================
    // TEST 4
    //
    // 再次按KEY2
    //
    // 验证松开以后能重新触发
    //========================================================

    $display("");
    $display("TEST 4 : PRESS KEY 2 AGAIN");


    press_key(
        4'h2
    );


    expect_key(
        4'h2
    );


    release_key();



    //--------------------------------------------------------
    // 仿真结束
    //--------------------------------------------------------

    $display("");
    $display("======================================");
    $display(" KEY SCAN SIMULATION FINISHED");
    $display("======================================");
    $display("");


    #500;

    $stop;

end


endmodule